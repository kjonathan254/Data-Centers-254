#!/usr/bin/env node
/**
 * DC254 Trust Brief - data sheet generator (brick #2).
 *
 * Pulls the Trust Engine numbers from PostHog and prints a markdown data
 * sheet: north-star funnel, conversion signals this week vs previous week,
 * guardrails, CSP tripwire detail, coverage notes. The agent (or editor)
 * wraps this in interpretation - the robot's hands, not the robot's brain.
 *
 * Works with a READ-ONLY personal API key (every call here is a read),
 * which is deliberate: this brick survives key downgrades.
 *
 * Usage:
 *   export POSTHOG_PERSONAL_API_KEY=phx_...
 *   node scripts/analytics/trust_brief.mjs                 # data sheet to stdout
 *   node scripts/analytics/trust_brief.mjs --out brief.md  # also write to file
 *
 * Env: POSTHOG_HOST (default https://us.posthog.com), POSTHOG_PROJECT_ID (default 674556).
 */

const HOST = (process.env.POSTHOG_HOST || "https://us.posthog.com").replace(/\/+$/, "");
const PROJECT = process.env.POSTHOG_PROJECT_ID || "674556";

if (!process.env.POSTHOG_PERSONAL_API_KEY) {
  console.error("POSTHOG_PERSONAL_API_KEY is not set (source .secrets/posthog.env)");
  process.exit(1);
}

const SIGNALS = [
  ["subscribe_optin_started", "Opt-ins started"],
  ["export_interest", "Tracker exports"],
  ["contact_message_sent", "Contact messages"],
  ["sponsor_click", "Sponsor clicks"],
  ["$pageview", "Human pageviews"],
];
const GUARDRAILS = [
  ["subscribe_honeypot_hit", "Honeypot hits"],
  ["sponsor_click_rejected", "Rejected sponsor clicks"],
  ["csp_violation", "CSP violations"],
];
const LAUNCH = "2026-10-19"; // PostHog capture live on site

function fail(context, status, body) {
  console.error(`FAIL ${context}: HTTP ${status}`);
  try { console.error(JSON.stringify(body).slice(0, 400)); } catch { console.error(String(body).slice(0, 400)); }
  process.exit(1);
}

async function api(path, opts = {}) {
  const res = await fetch(`${HOST}/api/projects/${PROJECT}${path}`, {
    ...opts,
    headers: {
      Authorization: `Bearer ${process.env.POSTHOG_PERSONAL_API_KEY}`,
      "Content-Type": "application/json",
      ...(opts.headers || {}),
    },
    body: opts.body ? JSON.stringify(opts.body) : undefined,
  });
  const json = await res.json().catch(() => ({}));
  if (!res.ok) fail((opts.method || "GET") + " " + path, res.status, json);
  return json;
}

// one multi-series trends query; returns {label: total}
async function countsFor(date_from, date_to) {
  const series = [...SIGNALS, ...GUARDRAILS].map(([event]) => ({ kind: "EventsNode", event }));
  const body = { query: { kind: "TrendsQuery", series, dateRange: date_to ? { date_from, date_to } : { date_from }, interval: "week" } };
  const out = await api(`/query/`, { method: "POST", body });
  if (out.error) fail("query", 500, { error: out.error });
  const totals = {};
  for (const s of out.results || []) {
    const ev = s.filter?.properties?.[0]?.values?.[0] || s.action?.name || s.label;
    totals[ev] = (totals[ev] || 0) + (s.count ?? s.data?.reduce((a, b) => a + b, 0) ?? 0);
  }
  return totals;
}

async function funnel30d() {
  const out = await api(`/query/`, {
    method: "POST",
    body: {
      query: {
        kind: "FunnelsQuery",
        series: [
          { kind: "EventsNode", event: "$pageview", name: "Read" },
          { kind: "EventsNode", event: "export_interest", name: "Engaged (tracker)" },
          { kind: "EventsNode", event: "subscribe_optin_started", name: "Opt-in started" },
        ],
        dateRange: { date_from: "-30d" },
        interval: "week",
        funnelsFilter: { funnelWindowInterval: 14, funnelWindowIntervalUnit: "day", funnelOrderType: "ordered" },
      },
    },
  });
  if (out.error) fail("funnel", 500, { error: out.error });
  return (out.results || []).map((s) => ({ name: s.name, count: s.count }));
}

async function cspDetail(limit = 12) {
  const d = await api(`/events/?event=csp_violation&limit=${limit}`);
  return (d.results || []).map((e) => ({
    when: e.timestamp.slice(0, 16).replace("T", " "),
    directive: e.properties?.directive || "?",
    blocked: (e.properties?.blocked || "").slice(0, 60),
    path: (e.properties?.path || "/").slice(0, 50),
  }));
}

async function sinceLaunch() {
  return countsFor(LAUNCH);
}

function fmtDelta(a, b) {
  if (a === 0 && b === 0) return "-";
  if (b === 0) return `new (+${a})`;
  const pct = Math.round(((a - b) / b) * 100);
  return `${pct >= 0 ? "+" : ""}${pct}%`;
}

async function main() {
  const today = new Date().toISOString().slice(0, 10);
  const [weekA, weekB, funnel, csp, launch] = await Promise.all([
    countsFor("-7d"),
    countsFor("-14d", "-7d"),
    funnel30d(),
    cspDetail(),
    sinceLaunch(),
  ]);

  const L = [];
  L.push(`# DC254 Trust Brief - data sheet (${today})`);
  L.push("");
  L.push(`_Generated by \`scripts/analytics/trust_brief.mjs\` from live PostHog data (project ${PROJECT}). Read-only safe._`);
  L.push("");
  L.push(`## 1. North-star funnel (30-day window, 14-day conversion limit)`);
  L.push("");
  L.push(funnel.length
    ? funnel.map((s, i) => `${i + 1}. ${s.name}: **${s.count}**`).join("\n")
    : "_no funnel rows returned_");
  L.push("");
  L.push(`## 2. Conversion signals (week vs previous week)`);
  L.push("");
  L.push(`| Signal | Last 7 days | Prior 7 days | Change | Since launch (${LAUNCH}) |`);
  L.push(`|---|---|---|---|---|`);
  for (const [ev, label] of SIGNALS) {
    L.push(`| ${label} | ${weekA[ev] || 0} | ${weekB[ev] || 0} | ${fmtDelta(weekA[ev] || 0, weekB[ev] || 0)} | ${launch[ev] || 0} |`);
  }
  L.push("");
  L.push(`## 3. Guardrails (week vs previous week)`);
  L.push("");
  L.push(`| Guardrail | Last 7 days | Prior 7 days | Since launch |`);
  L.push(`|---|---|---|---|`);
  for (const [ev, label] of GUARDRAILS) {
    L.push(`| ${label} | ${weekA[ev] || 0} | ${weekB[ev] || 0} | ${launch[ev] || 0} |`);
  }
  L.push("");
  L.push(`## 4. CSP tripwire detail (most recent first)`);
  L.push("");
  if (csp.length) {
    L.push(`| When (UTC) | Directive | Blocked origin | Page |`);
    L.push(`|---|---|---|---|`);
    for (const v of csp) L.push(`| ${v.when} | ${v.directive} | ${v.blocked} | ${v.path} |`);
  } else {
    L.push("_No violations captured._");
  }
  L.push("");
  L.push(`## 5. Coverage notes`);
  L.push("");
  L.push(`- Client events are consent-gated (DNT + opt-out respected) and bot-filtered at capture time.`);
  L.push(`- Server conversion events are zero-PII operational records, not gated.`);
  L.push(`- Funnel step 1 uses \`$pageview\`; tracker engagement uses \`export_interest\`; opt-in uses \`subscribe_optin_started\`.`);
  L.push(`- All event names are the contract with \`src/lib/posthog-server.ts\` - rename both sides together.`);
  L.push("");

  const sheet = L.join("\n");
  console.log(sheet);

  const outIdx = process.argv.indexOf("--out");
  if (outIdx > -1 && process.argv[outIdx + 1]) {
    const { writeFileSync } = await import("fs");
    writeFileSync(process.argv[outIdx + 1], sheet + "\n");
    console.error(`\nwritten -> ${process.argv[outIdx + 1]}`);
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
