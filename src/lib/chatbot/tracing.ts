/**
 * Sentry Agent Tracing attributes for Jibu — the pure half of the wiring.
 *
 * Jibu speaks the OpenAI chat-completions dialect over raw `fetch` (see
 * llm.ts), so none of Sentry's SDK auto-instrumentations (OpenAI client,
 * Vercel AI SDK, LangChain, the Groq SDK integration) can see those calls.
 * Sentry's documented answer for that shape is manual spans following the
 * gen_ai conventions (docs.sentry.io → Agent Tracing → Manual
 * Instrumentation); this module builds exactly the attribute sets those
 * conventions define, and route.ts wraps each real model call in a
 * `gen_ai.chat` span carrying them.
 *
 * Kept free of any @sentry import so the builders stay trivially unit-testable.
 *
 * Sizing: span attributes only accept primitives, so message arrays travel as
 * JSON strings. Every capture is bounded well below Sentry's per-attribute
 * truncation threshold — a debug trace must never become a payload problem.
 */

export type SpanAttributes = Record<string, string | number | boolean>;

export interface LlmCallContext {
  /**
   * Application-level chat session identifier (anonymous, generated by the
   * browser widget and reused across turns). Groups a multi-turn conversation
   * in Sentry's Conversations view via `gen_ai.conversation.id`. Per the
   * conventions: when there is no conversation id, omit the attribute — never
   * derive one from a trace or request id.
   */
  conversationId: string | null;
  /** The Jibu system prompt (identity + grounding rules). */
  system: string;
  /** Full messages array actually sent to the provider. */
  messages: { role: string; content: string }[];
  temperature: number;
  /** Which Jibu path requested the call. */
  path: "confidence_polish" | "weak_match_rescue";
}

// Caps chosen so a fully-populated span stays comfortably under Sentry's
// 8 KiB per-attribute truncation threshold even for the longest legal input
// (500-char question + 8 × 2000-char history turns + facts block).
const MAX_MESSAGES_JSON_CHARS = 6_000;
const MAX_SYSTEM_CHARS = 2_000;
const MAX_OUTPUT_TEXT_CHARS = 4_000;

/** JSON-encode a value for a span attribute, hard-bounded. */
export function truncateJson(value: unknown, limit: number): string {
  let json: string;
  try {
    json = JSON.stringify(value) ?? "";
  } catch {
    json = '"unserializable"';
  }
  return json.length <= limit ? json : json.slice(0, limit);
}

/** Low-cardinality, honest provider label for `gen_ai.provider.name`. */
export function providerName(id: string): string {
  return id.toLowerCase();
}

/**
 * Attributes set when a `gen_ai.chat` span starts (before the call, so
 * head-based sampling sees them, per the conventions page).
 */
export function llmSpanStartAttributes(
  provider: string,
  model: string,
  ctx: LlmCallContext,
): SpanAttributes {
  const attrs: SpanAttributes = {
    "gen_ai.operation.name": "chat",
    "gen_ai.request.model": model,
    "gen_ai.provider.name": providerName(provider),
    "gen_ai.agent.name": "Jibu",
    "gen_ai.request.temperature": ctx.temperature,
    // gen_ai.request.max_tokens is model-specific (tokenCeiling(model)) and is
    // spread in per attempt by the caller.
    "gen_ai.system_instructions": truncateJson(ctx.system, MAX_SYSTEM_CHARS),
    "gen_ai.input.messages": truncateJson(ctx.messages, MAX_MESSAGES_JSON_CHARS),
    "jibu.path": ctx.path,
  };
  if (ctx.conversationId) {
    attrs["gen_ai.conversation.id"] = ctx.conversationId;
  }
  return attrs;
}

/**
 * Attributes set when the model answered: response identity, the reply text
 * in the conventions' output-messages shape, finish reason and token usage
 * (prompt/completion tokens map to input/output; cached tokens would be a
 * subset of input, which Groq/NIM/HF dialects do not report today).
 */
export function llmSpanResponseAttributes(response: {
  model?: string | null;
  id?: string | null;
  text: string;
  finishReason?: string | null;
  inputTokens?: number | null;
  outputTokens?: number | null;
}): SpanAttributes {
  const attrs: SpanAttributes = {
    "gen_ai.output.messages": truncateJson(
      [{ role: "assistant", parts: [{ type: "text", content: response.text }] }],
      MAX_OUTPUT_TEXT_CHARS,
    ),
    "gen_ai.response.finish_reasons": truncateJson([response.finishReason ?? "stop"], 200),
  };
  if (response.model) attrs["gen_ai.response.model"] = response.model;
  if (response.id) attrs["gen_ai.response.id"] = response.id;
  if (response.inputTokens != null) attrs["gen_ai.usage.input_tokens"] = response.inputTokens;
  if (response.outputTokens != null) attrs["gen_ai.usage.output_tokens"] = response.outputTokens;
  return attrs;
}

/**
 * Attributes for the `gen_ai.invoke_agent` run span that wraps one /api/chat
 * request's model walk: the agent identity, the conversation grouping and the
 * same bounded input the chat spans saw.
 */
export function agentSpanAttributes(ctx: LlmCallContext, providers: string[]): SpanAttributes {
  const attrs: SpanAttributes = {
    "gen_ai.operation.name": "invoke_agent",
    "gen_ai.agent.name": "Jibu",
    "gen_ai.input.messages": truncateJson(ctx.messages, MAX_MESSAGES_JSON_CHARS),
    "jibu.providers": providers.join(","),
  };
  if (ctx.conversationId) {
    attrs["gen_ai.conversation.id"] = ctx.conversationId;
  }
  return attrs;
}
