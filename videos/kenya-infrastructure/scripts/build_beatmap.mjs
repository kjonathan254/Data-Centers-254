#!/usr/bin/env node
// Build src/beatmap.ts from measured TTS segment durations.
// Usage: node scripts/build_beatmap.mjs [seg8DurationOverride]

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const DIR = "public/audio/segments";
const FPS = 30;
const TOTAL = 1800; // 60s
const LEAD = 0.3; // s before first VO
const GAP = 0.25; // s between segments

const dur = (i) => {
  try {
    return parseFloat(
      execFileSync("ffprobe", [
        "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0",
        `${DIR}/seg${i}.wav`,
      ]).toString().trim(),
    );
  } catch {
    return 0;
  }
};

const segments = [];
for (let i = 1; i <= 8; i++) {
  segments.push({ i, d: dur(i) });
}
// seg8 override (if TTS still rate-limited, pass an estimate)
if (process.argv[2]) segments[7].d = parseFloat(process.argv[2]);
if (segments.some((s) => !s.d)) {
  console.error("MISSING SEGMENTS:", segments.filter((s) => !s.d).map((s) => s.i).join(", "));
  process.exit(1);
}

// beat i starts when segment i's lead-in begins
const starts = [];
let t = LEAD;
for (let i = 0; i < 8; i++) {
  starts.push(t);
  t += segments[i].d + GAP;
}
const voEnd = t - GAP;

// scale so the story fills exactly 60s
const scale = (TOTAL / FPS) / voEnd;
const IDS = ["hook", "cables", "landing", "backbone", "datacenter", "lastmile", "phone", "outro"];
// beat i starts when its VO starts (hook starts at 0);
// SHRINKS pulls a beat boundary earlier so slow openers don't drag (outro absorbs the time)
const SHRINKS = { hook: 1.7 }; // seconds trimmed from the hook->cables cut
const BEATS = {};
const frameStarts = starts.map((s, i) => {
  if (i === 0) return 0;
  const shrink = SHRINKS[IDS[i - 1]] ?? 0;
  return Math.max(Math.round((s - shrink) * FPS * scale), 30);
});
IDS.forEach((id, i) => {
  BEATS[id] = { start: frameStarts[i], end: 0 };
});
IDS.forEach((id, i) => {
  const next = IDS[i + 1];
  BEATS[id].end = next ? Math.max(BEATS[next].start, BEATS[id].start + 30) : TOTAL;
});

const CAPTIONS = {
  hook: "Where does the internet on your phone actually come from?",
  cables: "Under the Indian Ocean — seven international cables, one destination.",
  landing: "Mombasa. The internet comes ashore.",
  backbone: "Five hundred kilometres of national fibre backbone.",
  datacenter: "Data centres keep your apps close to home — local traffic stays local.",
  lastmile: "Mobile towers spread the signal to the mast nearest you.",
  phone: "Every tap makes the whole trip in a blink.",
  outro: "Cable. Coast. City. Cloud.",
};

const SCRIPT = [
  "Where does the internet on your phone actually come from? For Kenya, it starts at sea.",
  "Under the Indian Ocean, fibre optic cables carry almost all of Kenya's traffic. Seven cables. One destination.",
  "Mombasa. Where the internet comes ashore, and light becomes data.",
  "The national fibre backbone carries it five hundred kilometres inland, to Nairobi.",
  "Data centres keep your apps close to home, and local traffic stays local.",
  "Mobile towers spread the signal across the country. Kisumu, Garissa, the mast nearest you.",
  "Every tap, an M-Pesa payment, a call, a video, makes the trip in a blink.",
  "Cable, coast, city, cloud. That's Kenya. DC254.",
];

const fmtBeats = IDS.map(
  (id) => `  ${id}: { start: ${BEATS[id].start}, end: ${BEATS[id].end} },`
).join("\n");

const out = `// Beat map — GENERATED by scripts/build_beatmap.mjs from measured TTS durations.
// Voice: kazi @1.4 (z-ai TTS). Total VO ${voEnd.toFixed(2)}s scaled ${scale.toFixed(3)}x to fill 60s.
// Edit timings by regenerating, not by hand.

export type BeatId =
  | "hook"
  | "cables"
  | "landing"
  | "backbone"
  | "datacenter"
  | "lastmile"
  | "phone"
  | "outro";

export const BEAT_IDS: BeatId[] = [
  "hook",
  "cables",
  "landing",
  "backbone",
  "datacenter",
  "lastmile",
  "phone",
  "outro",
];

export const BEAT_LABELS: Record<BeatId, string> = {
  hook: "THE QUESTION",
  cables: "THE CABLES",
  landing: "THE LANDING",
  backbone: "THE BACKBONE",
  datacenter: "THE DATA CENTRE",
  lastmile: "THE LAST MILE",
  phone: "YOUR PHONE",
  outro: "KEEP WATCHING KENYA",
};

export const CAPTIONS: Record<BeatId, string> = {
  hook: "${CAPTIONS.hook}",
  cables: "${CAPTIONS.cables}",
  landing: "${CAPTIONS.landing}",
  backbone: "${CAPTIONS.backbone}",
  datacenter: "${CAPTIONS.datacenter}",
  lastmile: "${CAPTIONS.lastmile}",
  phone: "${CAPTIONS.phone}",
  outro: "${CAPTIONS.outro}",
};

// Narration script (voiceover, kazi @1.4):
export const SCRIPT: string[] = [
${SCRIPT.map((s) => `  "${s}",`).join("\n")}
];

export const FPS = ${FPS};
export const TOTAL = ${TOTAL}; // 60s

// frames
export const BEATS: Record<BeatId, { start: number; end: number }> = {
${fmtBeats}
};

export type BeatState = {
  id: BeatId;
  index: number;
  /** 0..1 progress through the beat */
  t: number;
  /** eased 0..1 with slow-in/out for camera moves */
  ease: number;
  /** frames elapsed inside beat */
  local: number;
};

export const beatOf = (frame: number): BeatState => {
  let index = 0;
  for (let i = 0; i < BEAT_IDS.length; i++) {
    if (frame >= BEATS[BEAT_IDS[i]].start) index = i;
  }
  const id = BEAT_IDS[index];
  const { start, end } = BEATS[id];
  const t = Math.min(1, Math.max(0, (frame - start) / Math.max(1, end - start)));
  const ease = t * t * (3 - 2 * t);
  return { id, index, t, ease, local: frame - start };
};

/** normalized in/out visibility window (0..1) for fade elements within a beat */
export const beatAlpha = (
  frame: number,
  id: BeatId,
  inFrames = 10,
  outFrames = 10,
): number => {
  const { start, end } = BEATS[id];
  const a = (frame - start) / inFrames;
  const b = (end - frame) / outFrames;
  return Math.min(1, Math.max(0, a), Math.max(0, b));
};

// VO segment starts in FINAL video seconds (after scaling) — used by the mixer
export const AUDIO_OFFSETS = ${JSON.stringify(starts.map((s) => Math.round(s * scale * 100) / 100))};
`;

writeFileSync("src/beatmap.ts", out);
writeFileSync(
  "src/beatmap.json",
  JSON.stringify({ BEATS, starts, voEnd, scale, segments, TOTAL, FPS, offsets: starts.map((s) => s * scale) }, null, 2),
);
console.log("beatmap written");
IDS.forEach((id) =>
  console.log(`  ${id.padEnd(11)} ${String(BEATS[id].start).padStart(4)}\u2192${String(BEATS[id].end).padStart(4)}  (${((BEATS[id].end - BEATS[id].start) / FPS).toFixed(2)}s)`),
);
console.log(`  VO ends at ${(voEnd * scale).toFixed(2)}s of 60s`);
